function detectLanguage(): State["guestLanguage"] {
  const nav = (typeof navigator !== "undefined" ? navigator.language : "pt").toLowerCase();
  if (nav.startsWith("es")) return "es";
  if (nav.startsWith("en")) return "en";
  return "pt";
}
